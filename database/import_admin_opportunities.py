def run(apply=False):
    today_utc = datetime.now(timezone.utc).date()
    expired_publications = [
        item["title"]
        for item in OPPORTUNITIES
        if item.get("status") == "published"
        and item.get("deadline")
        and date.fromisoformat(item["deadline"]) < today_utc
    ]
    if expired_publications:
        raise ValueError(
            "Published catalog entries now have past deadlines; review and reclassify them before importing: "
            + "; ".join(expired_publications)
        )

    prepared_pairs = set()
    prepared_sources = {}
    for item in OPPORTUNITIES:
        title_key = " ".join(item["title"].casefold().split())
        organization_key = " ".join(item["organization"].casefold().split())
        parsed = urlsplit(item["source_url"])
        source_key = urlunsplit((parsed.scheme.casefold(), parsed.netloc.casefold(), parsed.path.rstrip("/"), parsed.query, ""))
        if (title_key, organization_key) in prepared_pairs:
            raise ValueError(f"Duplicate prepared opportunity title and organization: {item['title']}")
        prepared_pairs.add((title_key, organization_key))
        prepared_sources[source_key] = prepared_sources.get(source_key, 0) + 1

    def duplicate_key(row):
        parsed = urlsplit(row["source_url"] or "")
        source_key = urlunsplit((parsed.scheme.casefold(), parsed.netloc.casefold(), parsed.path.rstrip("/"), parsed.query, ""))
        return (
            " ".join((row["title"] or "").casefold().split()),
            " ".join((row["organization_name"] or "").casefold().split()),
            source_key,
        )

    shared_source_urls = {source for source, count in prepared_sources.items() if count > 1}

    def is_duplicate(item, known):
        candidate = duplicate_key({"title": item["title"], "organization_name": item["organization"], "source_url": item["source_url"]})
        return any(
            candidate[:2] == row[:2]
            or (candidate[2] == row[2] and candidate[2] not in shared_source_urls)
            for row in known
        )

    with psycopg2.connect(Config.DATABASE_URL) as conn:
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            cur.execute("SELECT current_database() AS database_name")
            database_name = cur.fetchone()["database_name"]
            if database_name != "skillbridge":
                raise RuntimeError("Refusing to import: configured database is not skillbridge.")
            cur.execute("SELECT id FROM accounts WHERE role='developer' ORDER BY id LIMIT 1")
            admin = cur.fetchone()
            if not admin:
                raise RuntimeError("No Platform Administrator account exists; create one through the existing admin bootstrap workflow first.")
            if apply:
                cur.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", ("skillbridge-stage7.1-admin-catalog",))
            cur.execute("SELECT title,organization_name,source_url FROM jobs WHERE owner_type='ADMIN'")
            existing = [duplicate_key(row) for row in cur.fetchall()]
            to_insert = []
            skipped = []
            for item in OPPORTUNITIES:
                if is_duplicate(item, existing):
                    skipped.append(item["title"])
                    continue
                if item["classification"] == VERIFIED and not item.get("verified_at"):
                    raise ValueError(f"Verified opportunity lacks a recorded verification date: {item['title']}")
                to_insert.append(item)
            if not apply:
                print(f"Dry run on {database_name}: prepared {len(OPPORTUNITIES)}, would insert {len(to_insert)}, would skip {len(skipped)} existing duplicate(s). Existing admin rows: {len(existing)}. Shared official overview URLs: {len(shared_source_urls)} (matched by title and organization). No records changed.")
                if skipped:
                    print("Skipped existing titles: " + "; ".join(skipped))
                return

            inserted = 0
            for item in to_insert:
                skill_ids = []
                for name, required in item["skills"]:
                    cur.execute("INSERT INTO skills(name,category) VALUES(%s,%s) ON CONFLICT(name) DO NOTHING", (name, "Programming"))
                    cur.execute("SELECT id FROM skills WHERE name=%s", (name,))
                    skill_ids.append((cur.fetchone()["id"], required))

                verified_at = datetime.combine(date.fromisoformat(item["verified_at"]), time.min, tzinfo=timezone.utc) if item.get("verified_at") else None
                cur.execute(
                    """INSERT INTO jobs (
                           company_id,recruiter_id,owner_type,created_by_admin,organization_name,
                           title,job_type,opportunity_type,work_mode,location,description,requirements,
                           salary_min,salary_max,deadline,status,opportunity_category,experience_level,
                           paid_status,eligibility,application_url,application_mode,positions,
                           source,source_classification,source_url,source_verified_by,source_verified_at,
                           is_verified,is_sample,eligible_branches
                       ) VALUES (
                           NULL,NULL,'ADMIN',%s,%s,%s,%s,%s,%s,%s,%s,%s,
                           %s,%s,%s,%s,%s,%s,%s,%s,%s,'external',NULL,
                           'admin_curated',%s,%s,%s,%s,%s,FALSE,%s
                       ) RETURNING id""",
                    (
                        admin["id"], item["organization"], item["title"], item.get("job_type"), item["opportunity_type"],
                        item.get("work_mode"), item["location"], item["description"], None,
                        item.get("salary_min"), item.get("salary_max"), item.get("deadline"), item.get("status", "draft"),
                        item["category"],
                        item.get("experience", "Student"), item.get("paid_status", "none"), item["eligibility"],
                        item["application_url"], item["classification"], item["source_url"], admin["id"] if verified_at else None, verified_at,
                        item["classification"] == VERIFIED, item["branches"],
                    ),
                )
                job_id = cur.fetchone()["id"]
                for skill_id, required in skill_ids:
                    cur.execute(
                        "INSERT INTO job_skills(job_id,skill_id,is_required,min_proficiency) VALUES(%s,%s,%s,'Intermediate') ON CONFLICT(job_id,skill_id) DO NOTHING",
                        (job_id, skill_id, required),
                    )
                inserted += 1
    print(f"Import complete on skillbridge: inserted {inserted}, skipped existing {skipped}. No existing job rows were updated or deleted.")


